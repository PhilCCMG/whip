import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { NewspaperSchema, type Newspaper } from '@whip/contracts';
import type { GameState } from '@whip/domain';
import { describe, expect, it } from 'vitest';
import { realRuntime } from '.';

/**
 * Regenerates the owner-facing newspaper samples and the web mock fixture from the real engine:
 *
 *   WRITE_NEWSPAPER_SAMPLES=1 pnpm --filter @whip/api exec vitest run newspaper-samples
 *
 * Without the variable it only checks that the sample editions parse with the contracts schema.
 */
const { engine, projections } = realRuntime;
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../../../..');
const SEED = 20290903;
const player = {
  firstName: 'Alex',
  lastName: 'Morgan',
  gender: 'nonbinary',
  strength: 'negotiation',
  ideologyPreset: 'independent',
} as const;

/** A short scripted career: a meeting, a speech, some cultivation, then the Second Reading. */
const SCRIPT: Record<number, { kind: string; params: Record<string, unknown> }[]> = {
  1: [
    { kind: 'meet_politician', params: { targetId: 'pol_bernadette_walsh' } },
    {
      kind: 'support_legislation',
      params: { billId: 'bill.housing_delivery', lobbyTargetIds: ['pol_tom_fairley'] },
    },
  ],
  2: [{ kind: 'build_relationship', params: { targetId: 'pol_gareth_pryce' } }],
  3: [{ kind: 'seek_endorsement', params: { targetId: 'pol_ken_bramley' } }],
};

function editions(): { opening: Newspaper; weeks: Newspaper[] } {
  const created = engine.create({ scenarioKey: 'first_weeks', seed: SEED, player });
  const summary = (s: GameState) => ({
    id: 'sample',
    name: 'Sample',
    scenarioKey: 'first_weeks' as const,
    status: 'active' as const,
    simDate: s.meta.date,
    turn: s.meta.turn,
    revision: 1,
    playerName: 'Alex Morgan',
    simulationVersion: engine.version,
    createdAt: '2026-01-01T00:00:00.000Z',
    updatedAt: '2026-01-01T00:00:00.000Z',
  });
  const opening = projections.careerOverview(created.state, summary(created.state)).briefing
    .newspaper;
  let s = created.state;
  const weeks: Newspaper[] = [];
  for (let turn = 1; turn <= 6; turn++) {
    for (const a of SCRIPT[turn] ?? []) {
      const r = engine.planAction(s, { kind: a.kind as never, params: a.params });
      if (r.ok) s = r.state;
    }
    const out = engine.advance(s);
    const report = projections.turnReport({ before: s, output: out, revision: turn + 1 });
    if (report.newspaper) weeks.push(report.newspaper);
    s = out.state;
  }
  if (!opening) throw new Error('no opening edition');
  return { opening, weeks };
}

function markdown(title: string, note: string, p: Newspaper): string {
  const lines = [
    `## ${title}`,
    '',
    `_${note}_`,
    '',
    `> **${p.masthead.title.toUpperCase()}** · _${p.masthead.slogan}_  `,
    `> ${p.masthead.edition} · ${p.masthead.date} · ${p.masthead.price}`,
    '',
  ];
  const article = (a: Newspaper['lead'], lead = false) => {
    lines.push(lead ? `#### ${a.headline}` : `**${a.headline}**`, '');
    if (a.standfirst) lines.push(`_${a.standfirst}_`, '');
    if (a.byline) lines.push(`<small>${a.byline}</small>`, '');
    if (a.body) lines.push(a.body, '');
  };
  lines.push('### Lead', '');
  article(p.lead, true);
  for (const s of p.sections) {
    lines.push(`### ${s.title}`, '');
    for (const a of s.articles) article(a);
  }
  return lines.join('\n');
}

describe('newspaper samples', () => {
  const { opening, weeks } = editions();

  it('sample editions parse with the contracts schema', () => {
    for (const p of [opening, ...weeks]) NewspaperSchema.parse(p);
    expect(weeks.length).toBe(6);
  });

  it.skipIf(!process.env.WRITE_NEWSPAPER_SAMPLES)('writes the samples doc and web fixture', () => {
    const division = weeks[3]!; // the week of the Second Reading (turn 4)
    const quiet = weeks[1]!; // turn 2: no division, no crisis
    const doc = [
      '# Newspaper samples',
      '',
      'Generated by the real engine (`apps/api/src/infrastructure/engine/newspaper-samples.test.ts`,',
      `seed ${SEED}, First Weeks, player Alex Morgan, Member for Ashby and Wold). Regenerate with`,
      '`WRITE_NEWSPAPER_SAMPLES=1 pnpm --filter @whip/api exec vitest run newspaper-samples`.',
      'Everyone and everything named is fictional.',
      '',
      markdown('1. Opening edition (turn 1)', 'Printed at campaign creation.', opening),
      '',
      '---',
      '',
      markdown(
        '2. Division week (turn 4: Second Reading)',
        'The week of the three-line-whipped Second Reading of the Housing Delivery Bill.',
        division,
      ),
      '',
      '---',
      '',
      markdown(
        '3. Quiet week (turn 2)',
        'No division, no crisis: gossip, sketch and filler.',
        quiet,
      ),
      '',
    ].join('\n');
    const docPath = resolve(ROOT, 'docs/architecture/samples/newspaper-samples.md');
    mkdirSync(dirname(docPath), { recursive: true });
    writeFileSync(docPath, doc);

    const fixture = [
      '/**',
      ' * Sample newspaper editions for mock mode, generated by the real engine (First Weeks, seed',
      ` * ${SEED}) via apps/api/src/infrastructure/engine/newspaper-samples.test.ts. Do not edit by`,
      ' * hand: regenerate with WRITE_NEWSPAPER_SAMPLES=1. Both values parse with NewspaperSchema.',
      ' */',
      "import type { Newspaper } from '@whip/contracts';",
      '',
      '/** The Second Reading week (turn 4): a division-led edition. */',
      `export const newspaperFixture: Newspaper = ${JSON.stringify(division, null, 2)};`,
      '',
      '/** The opening edition printed at campaign creation (turn 1). */',
      `export const openingNewspaperFixture: Newspaper = ${JSON.stringify(opening, null, 2)};`,
      '',
      '/** A quiet week (turn 2). */',
      `export const quietNewspaperFixture: Newspaper = ${JSON.stringify(quiet, null, 2)};`,
      '',
    ].join('\n');
    writeFileSync(resolve(ROOT, 'apps/web/src/mocks/newspaper-fixture.ts'), fixture);
  });
});
